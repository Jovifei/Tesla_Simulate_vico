function contract = s12_v12_texture_simulink_contract()
%S12_V12_TEXTURE_SIMULINK_CONTRACT Fixed research-only Simulink port contract.
% The default texture weight is zero, so the legacy v1.2 path is unchanged.

contract.version = "s12-v12-texture-residual-simulink-v1";
contract.scope = "RESEARCH_ONLY_NOT_PRODUCT_AUDIO";
contract.default_texture_weight = 0;
contract.inputs = struct( ...
    "vehicle_state", struct("dimensions", [9, 1], "sample_time_s", 0.02), ...
    "texture_residual", struct("dimensions", [960, 1], "sample_time_s", 0.02), ...
    "texture_weight", struct("dimensions", [1, 1], "sample_time_s", 0.02));
contract.outputs = struct( ...
    "pre_ptr", struct("dimensions", [960, 1], "sample_time_s", 0.02), ...
    "pcm", struct("dimensions", [960, 2], "sample_time_s", 0.02));
contract.topology = [ ...
    "Vehicle State [9,1] -> Source MATLAB Function [960,1]", ...
    "Source [960,1] + Texture Residual [960,1] + Weight [1,1] -> Texture Mixer [960,1]", ...
    "Texture Mixer [960,1] -> Frozen Radiation Adapter [960,1] -> Stereo Renderer [960,2]"];
contract.gates = struct( ...
    "finite", true, "peak_bounded", true, "state_inference", false, ...
    "default_product_route", false, "frozen_radiation_changed", false, ...
    "requires_matlab_runtime", true, "requires_update_diagram", true, ...
    "requires_active_compile", true, "requires_90s_simulation", true);
end
