function [specification, shared] = readCaseSpecification(caseId)
root = fileparts(mfilename("fullpath"));
shared = jsondecode(fileread(fullfile(root, "config", ...
    "radiation_boundary_cases.json")));
cases = normalizeCaseList(shared.cases);
ids = strings(1, numel(cases));
for index = 1:numel(cases)
    ids(index) = string(cases{index}.case_id);
end
index = find(ids == caseId, 1);
if isempty(index)
    error("S12:Radiation:UnsupportedCase", "Unknown radiation benchmark case '%s'.", caseId);
end
specification = cases{index};
end

function cases = normalizeCaseList(value)
if isstruct(value)
    cases = num2cell(value);
elseif iscell(value)
    cases = value;
else
    error("S12:Radiation:InvalidCaseConfig", "Case configuration must be an object array.");
end
if ~all(cellfun(@(item) isstruct(item) && isscalar(item), cases))
    error("S12:Radiation:InvalidCaseConfig", "Every case configuration must be one object.");
end
end

function definition = materializeDefinition(specification, physical)
gamma = 1.4;
pressure = physical.rho0 * physical.c0^2 / gamma;
inputSignal = normalizeInputSignal(specification.input_signal);
frequency = inputFrequency(inputSignal);
amplitude = inputAmplitude(inputSignal);
definition = struct( ...
    "case_id", string(specification.case_id), ...
    "category", string(specification.category), ...
    "execution_mode", string(specification.execution_mode), ...
    "boundary_type", string(specification.boundary_type), ...
    "boundary_limit", string(specification.boundary_limit), ...
    "gamma", gamma, "pipe_length_m", 0.01, ...
    "ambient_state", [physical.rho0; 0; pressure / (gamma - 1)], ...
    "small_signal_limit", 0.005, ...
    "input_signal", inputSignal, ...
    "input_waveform_id", string(specification.input_waveform_id), ...
    "input_amplitude_pa", amplitude, ...
    "frequency_hz", frequency, ...
    "ka", 2 * pi * frequency * physical.pipe_radius_m / physical.c0, ...
    "end_time_s", double(specification.end_time_s), ...
    "initial_radiation_output_pa", fieldOr(specification, ...
        "initial_radiation_output_pa", 0), ...
    "amplitude_scales", reshape(fieldOr(specification, "amplitude_scales", 1), 1, []));
end

function plan = buildRunPlan(definition, settings)
empty = struct("grid_cell_count", 0, "cfl", 0, "amplitude_scale", 1);
switch definition.execution_mode
    case "nominal"
        plan = struct("grid_cell_count", settings.nominal_grid_cell_count, ...
            "cfl", settings.cfl, "amplitude_scale", 1);
    case "grid"
        plan = repmat(empty, 1, numel(settings.grid_cell_counts));
        for index = 1:numel(plan)
            plan(index) = struct("grid_cell_count", settings.grid_cell_counts(index), ...
                "cfl", settings.cfl, "amplitude_scale", 1);
        end
    case "time"
        plan = repmat(empty, 1, numel(settings.cfl_scan));
        for index = 1:numel(plan)
            plan(index) = struct("grid_cell_count", ...
                settings.time_convergence_grid_cell_count, ...
                "cfl", settings.cfl_scan(index), "amplitude_scale", 1);
        end
    case "amplitude"
        plan = repmat(empty, 1, numel(definition.amplitude_scales));
        for index = 1:numel(plan)
            plan(index) = struct("grid_cell_count", settings.nominal_grid_cell_count, ...
                "cfl", settings.cfl, ...
                "amplitude_scale", definition.amplitude_scales(index));
        end
    otherwise
        plan = struct([]);
end
end

function windows = measurementWindows(shared, definition)
travel = definition.pipe_length_m / 343;
windows = struct("id", string(shared.measurement_window_id), ...
    "incident_start_s", 0, "reflected_start_s", 2 * travel, ...
    "end_time_s", definition.end_time_s, ...
    "window_function", "rectangular_fixed.v1", ...
    "phase_convention", "exp(+j*omega*t)");
end

function package = packageForCase(physical, boundaryLimit)
package = callRadiation("s12_radiation_boundary_package", physical);
if boundaryLimit == "fitted", return, end
package.state_space_A = zeros(2); package.state_space_B = zeros(2,1);
package.state_space_C = zeros(1,2); package.initial_state = zeros(2,1);
switch boundaryLimit
    case "open", package.state_space_D = -1;
    case "matched", package.state_space_D = 0;
    case "rigid", package.state_space_D = 1;
    otherwise, error("S12:Radiation:InvalidBoundary", "Unknown boundary limit.");
end
package.asset_sha256 = limitHash(boundaryLimit);
package.source_commit = "sprint_4d_b_limit_contract.v1";
end

function state = initialRadiationState(definition, package)
state = zeros(2,1);
if definition.initial_radiation_output_pa == 0 || ...
        all(package.state_space_C == 0, "all")
    return
end
row = package.state_space_C;
state = row.' * (definition.initial_radiation_output_pa / (row * row.'));
end

