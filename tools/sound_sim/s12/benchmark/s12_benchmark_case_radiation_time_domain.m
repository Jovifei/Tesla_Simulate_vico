reference = struct("incoming_pressure_pa", zeros(size(fvm.trace_time_s)), ...
    "reference_reflection", zeros(1, count), "frequency_hz", zeros(1, count), ...
    "ka", zeros(1, count));
end

function value = zeroInputDecays(incomingPressure)
value = isfinite(incomingPressure(end)) && ...
    abs(incomingPressure(end)) <= abs(incomingPressure(1));
end

function value = reflectionEstimate(config)
physical = config.physical_definition;
frequency = reflectionFrequencies(config.case_definition, physical);
ka = 2 * pi * frequency * physical.pipe_radius_m / physical.c0;
switch config.case_definition.boundary_limit
    case "fitted"
        reference = callRadiation("s12_radiation_unflanged_reference", ka, physical);
        measured = callRadiation("s12_radiation_unflanged_pade_fit", ka, physical);
        referenceReflection = reference.reflection;
        measuredReflection = measured.reflection;
    case "open"
        referenceReflection = -ones(size(ka));
        measuredReflection = referenceReflection;
    case "matched"
        referenceReflection = zeros(size(ka));
        measuredReflection = referenceReflection;
    case "rigid"
        referenceReflection = ones(size(ka));
        measuredReflection = referenceReflection;
    otherwise
        error("S12:Radiation:InvalidBoundary", "Unknown boundary limit.");
end
complexError = abs(measuredReflection - referenceReflection);
[maximumError, index] = max(complexError);
magnitudeError = abs(abs(measuredReflection) - abs(referenceReflection));
phaseError = abs(angle(exp(1i * (angle(measuredReflection) - ...
    angle(referenceReflection)))));
value = struct("measured", measuredReflection(index), ...
    "reference", referenceReflection(index), "frequency_hz", frequency(index), ...
    "ka", ka(index), "complex_error", maximumError, ...
    "magnitude_error", max(magnitudeError), "phase_error", max(phaseError));
end

function frequency = reflectionFrequencies(definition, physical)
frequency = reshape(double(definition.frequency_hz), 1, []);
frequency = frequency(isfinite(frequency) & frequency > 0);
if isempty(frequency)
    frequency = physical.accepted_ka * physical.c0 / ...
        (2 * pi * physical.pipe_radius_m);
end
end

function value = traceEnergy(signal, time)
value = sum(signal(1:end-1).^2 .* diff(time));
end

function value = arrivalTime(signal, time)
threshold = 0.05 * max(abs(signal));
index = find(abs(signal) >= threshold, 1);
if isempty(index), value = time(end); else, value = time(index); end
end

function value = prearrivalFraction(fvm, arrivalReference)
allEnergy = traceEnergy(fvm.trace_incoming_pressure_pa, fvm.trace_time_s);
indices = fvm.trace_time_s < arrivalReference;
if nnz(indices) < 2 || allEnergy <= realmin
    value = 0;
    return
end
value = traceEnergy(fvm.trace_incoming_pressure_pa(indices), ...
    fvm.trace_time_s(indices)) / allEnergy;
end

function value = amplitudeLinearityError(values)
if numel(values.amplitude) < 2 || any(values.amplitude <= 0)
    value = 0;
    return
end
coefficient = values.measured_reflection;
value = max(abs(coefficient - coefficient(1))) / ...
    max(abs(coefficient(1)), realmin);
end

function values = observedOrder(scale, error)
[scale, order] = sort(scale, "descend");
error = error(order);
values = NaN(1, max(numel(scale) - 1, 0));
for index = 1:numel(values)
    if scale(index) > scale(index + 1) && error(index) > 0 && error(index + 1) > 0
        values(index) = log(error(index) / error(index + 1)) / ...
            log(scale(index + 1) / scale(index));
    end
end
end

