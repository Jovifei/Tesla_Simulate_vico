function definition = s12_benchmark_case_radiation_time_domain(caseId)
%S12_BENCHMARK_CASE_RADIATION_TIME_DOMAIN Define one config-owned 4D-B case.
arguments
    caseId (1,1) string
end
definition = struct("configure", @(profile) configureCase(caseId, profile), ...
    "run", @runCase, "analyze", @analyzeCase, "accept", @acceptCase);
end

function config = configureCase(caseId, profile)
settings = profile.radiation_boundary_time_domain;
physical = callRadiation("s12_radiation_case_definition", ...
    string(settings.validation_profile));
[specification, shared] = readCaseSpecification(caseId);
definition = materializeDefinition(specification, physical);
package = packageForCase(physical, definition.boundary_limit);
package.initial_state = initialRadiationState(definition, package);
config = struct( ...
    "case_id", caseId, ...
    "category", string(specification.category), ...
    "physical_definition", physical, ...
    "radiation_package", package, ...
    "radiation_package_sha256", string(package.asset_sha256), ...
    "grid_cell_counts", reshape(settings.grid_cell_counts, 1, []), ...
    "cfl", double(settings.cfl), ...
    "cfl_scan", reshape(settings.cfl_scan, 1, []), ...
    "max_steps", double(settings.max_steps), ...
    "sample_stride", double(settings.sample_stride), ...
    "case_definition", definition, ...
    "run_plan", buildRunPlan(definition, settings), ...
    "measurement_windows", measurementWindows(shared, definition), ...
    "probe_locations", string(shared.probe_locations), ...
    "acceptance_limits", settings.acceptance, ...
    "threshold_evidence", string(settings.acceptance.evidence_id));
end

function raw = runCase(config)
if config.case_definition.execution_mode == "unified_evidence"
    raw = struct("config", config, "runs", struct([]), ...
        "evidence", readUnifiedEvidence(), "runtime_seconds", 0);
    return
end
started = tic;
plan = config.run_plan;
runs = repmat(struct("grid_cell_count", 0, "cfl", 0, ...
    "amplitude_scale", 0, "fvm", struct()), 1, numel(plan));
for index = 1:numel(plan)
    definition = scaledDefinition(config.case_definition, plan(index).amplitude_scale);
    fvmConfig = struct( ...
        "gamma", definition.gamma, ...
        "pipe_length_m", definition.pipe_length_m, ...
        "initial_state", initialState(definition, plan(index).grid_cell_count), ...
        "ambient_state", definition.ambient_state, ...
        "end_time_s", definition.end_time_s, ...
        "cfl", plan(index).cfl, ...
        "max_steps", config.max_steps, ...
        "small_signal_limit", definition.small_signal_limit, ...
        "radiation_package", config.radiation_package, ...
        "input_signal", definition.input_signal, ...
        "initial_radiation_state", config.radiation_package.initial_state);
    runs(index) = struct( ...
        "grid_cell_count", plan(index).grid_cell_count, ...
        "cfl", plan(index).cfl, ...
        "amplitude_scale", plan(index).amplitude_scale, ...
        "fvm", callRadiation("s12_run_radiation_boundary_fixed_driver", fvmConfig));
end
raw = struct("config", config, "runs", runs, "evidence", struct(), ...
    "runtime_seconds", toc(started));
end

function analysis = analyzeCase(raw)
if raw.config.case_definition.execution_mode == "unified_evidence"
    analysis = evidenceAnalysis(raw.config, raw.evidence);
    return
end
config = raw.config;
count = numel(raw.runs);
values = newValueStore(count);
plotData = repmat(struct("time", [], "outgoing", [], "incoming", [], ...
    "reference", []), 1, count);
for index = 1:count
    run = raw.runs(index);
    fvm = run.fvm;
    isZeroInput = inputAmplitude(config.case_definition.input_signal) == 0;
    if isZeroInput
        reference = zeroInputReference(fvm);
    else
        reference = callRadiation("s12_radiation_time_domain_reference", ...
            config.radiation_package, ...
            fvm.trace_time_s, fvm.trace_outgoing_pressure_pa);
        difference = fvm.trace_incoming_pressure_pa - reference.incoming_pressure_pa;
        scale = max([max(abs(reference.incoming_pressure_pa)), ...
            max(abs(fvm.trace_outgoing_pressure_pa)), realmin]);
        reflection = reflectionEstimate(config);
        values.waveform_l1(index) = mean(abs(difference)) / scale;
        values.waveform_linf(index) = max(abs(difference)) / scale;
        values.reflection_complex(index) = reflection.complex_error;
        values.reflection_magnitude(index) = reflection.magnitude_error;
        values.reflection_phase(index) = reflection.phase_error;
        values.reference_reflection(index) = reflection.reference;
        values.measured_reflection(index) = reflection.measured;
        values.frequency_hz(index) = reflection.frequency_hz;
        values.ka(index) = reflection.ka;
    end
    values.zero_input_decay(index) = ~isZeroInput || ...
        zeroInputDecays(fvm.trace_incoming_pressure_pa);
    values.minimum_density(index) = min(fvm.final_state(1, :));
    values.minimum_pressure(index) = minimumPressureOf(fvm.final_state, ...
        config.case_definition.gamma);
    values.maximum_cfl(index) = fvm.maximum_cfl;
    values.retry(index) = fvm.qualification.retry_count;
    values.rejected(index) = fvm.qualification.rejected_step_count;
    values.rollback(index) = fvm.qualification.rollback_count;
    values.amplification(index) = ...
        fvm.qualification.maximum_radiation_stage_pole_amplification;
    values.time_step(index) = max(diff(fvm.trace_time_s));
    values.sample_rate(index) = 1 / values.time_step(index);
    values.incident_energy(index) = traceEnergy( ...
        fvm.trace_outgoing_pressure_pa, fvm.trace_time_s);
    values.reflected_energy(index) = traceEnergy( ...
        fvm.trace_incoming_pressure_pa, fvm.trace_time_s);
    values.radiated_energy(index) = max(values.incident_energy(index) - ...
        values.reflected_energy(index), 0);
    values.boundary_state_energy(index) = norm(fvm.final_radiation_state)^2;
    values.arrival_reference(index) = arrivalTime( ...
        reference.incoming_pressure_pa, fvm.trace_time_s);
    values.arrival_measured(index) = arrivalTime( ...
        fvm.trace_incoming_pressure_pa, fvm.trace_time_s);
    values.prearrival(index) = prearrivalFraction(fvm, values.arrival_reference(index));
    values.grid_cell_count(index) = run.grid_cell_count;
    values.cfl(index) = run.cfl;
    values.amplitude(index) = inputAmplitude(config.case_definition.input_signal) * ...
        run.amplitude_scale;
    values.runner_id(index) = string(fvm.runner_id);
    values.runner_version(index) = string(fvm.runner_version);
    values.driver_path(index) = string(fvm.driver_path);
    values.driver_sha256(index) = string(fvm.driver_sha256);
    values.execution_mode(index) = string(fvm.execution_mode);
    values.physical_step_count(index) = double(fvm.physical_step_count);
    values.sim_call_count(index) = double(fvm.sim_call_count);
    values.compile_count(index) = double(fvm.compile_count);
    values.boundary_crossing_count(index) = double(fvm.boundary_crossing_count);
    plotData(index) = struct("time", fvm.trace_time_s, ...
        "outgoing", fvm.trace_outgoing_pressure_pa, ...
        "incoming", fvm.trace_incoming_pressure_pa, ...
        "reference", reference.incoming_pressure_pa);
end
metrics = canonicalMetrics(config, values, raw.runtime_seconds);
analysis = struct("metrics", metrics, "plot", struct("traces", plotData));
end

