namespace {
// Cylinder storage is [1,3,5,7] then [2,4,6,8]. Firing order is 1-8-7-2-6-5-4-3.
constexpr int firingSlot[2][4] = {{0, 7, 5, 2}, {3, 6, 4, 1}};
constexpr double primaryExtraCm[2][4] = {{2, 1, 3, 5}, {1, 5, 7, 0}};

void initializeFlow(Function &function, const double (&cfm)[10]) {
    function.initialize(10, 50 * units::thou);
    for (int i = 0; i < 10; ++i) {
        function.addSample(i * 50 * units::thou, GasSystem::k_28inH2O(cfm[i]));
    }
}

// Same sampled harmonic profile as scripting/include/actions.h:437-462.
void initializeLobe(Function &function, double durationAt50Thou) {
    constexpr int steps = 256;
    constexpr double gamma = 1.1;
    constexpr double lift = 551 * units::thou;
    const double s = std::pow(2 * 50 * units::thou / lift, 1 / gamma) - 1;
    const double k = std::acos(s) / (durationAt50Thou / 4);
    const double extent = constants::pi / k;
    const double step = extent / (steps - 5.0);

    function.initialize(2 * steps - 1, step);
    function.addSample(0.0, lift);
    for (int i = 1; i < steps; ++i) {
        const double x = i * step;
        const double y = (x >= extent)
            ? 0.0
            : lift * std::pow(0.5 + 0.5 * std::cos(k * x), gamma);
        function.addSample(x, y);
        function.addSample(-x, y);
    }
}
} // namespace

struct OfflineModel::Resources {
    Function intakeFlow;
    Function exhaustFlow;
    Function intakeLobe;
    Function exhaustLobe;
    Function timingCurve;
    Function meanPistonSpeedToTurbulence;
    Function turbulenceToFlameSpeedRatio;
    Camshaft intakeCams[2];
    Camshaft exhaustCams[2];
    StandardValvetrain valvetrains[2];

    ~Resources() {
        for (int bank = 0; bank < 2; ++bank) {
            intakeCams[bank].destroy();
            exhaustCams[bank].destroy();
        }
        intakeFlow.destroy();
        exhaustFlow.destroy();
        intakeLobe.destroy();
        exhaustLobe.destroy();
        timingCurve.destroy();
        meanPistonSpeedToTurbulence.destroy();
        turbulenceToFlameSpeedRatio.destroy();
    }
};

OfflineModel::OfflineModel() = default;

OfflineModel::~OfflineModel() {
    destroy();
}

void OfflineModel::initialize() {
    if (engineInitialized_) {
        throw std::logic_error("OfflineModel is already initialized");
    }
    resources_ = std::make_unique<Resources>();
    Resources &r = *resources_;

    // Source: assets/engines/atg-video-2/07_gm_ls.mr at 85f7c3b.
    const double intakeCfm[10] = {0, 1, 103, 156, 214, 249, 268, 280, 280, 281};
    const double exhaustCfm[10] = {0, 1, 72, 113, 160, 196, 222, 235, 245, 246};
    initializeFlow(r.intakeFlow, intakeCfm);
    initializeFlow(r.exhaustFlow, exhaustCfm);
    initializeLobe(r.intakeLobe, 234 * units::deg);
    initializeLobe(r.exhaustLobe, 235 * units::deg);

    r.timingCurve.initialize(9, units::rpm(1000));
    const double timingDegrees[9] = {12, 12, 20, 30, 40, 40, 40, 40, 40};
    for (int i = 0; i < 9; ++i) {
        r.timingCurve.addSample(units::rpm(i * 1000), timingDegrees[i] * units::deg);
    }
    // Same helper generated by EngineNode::buildEngine, not a fitted table.
    r.meanPistonSpeedToTurbulence.initialize(30, 1.0);
    for (int i = 0; i < 30; ++i) {
        r.meanPistonSpeedToTurbulence.addSample(i, i * 0.5);
    }
    r.turbulenceToFlameSpeedRatio.initialize(10, 5.0);
    const double flameRatios[10] = {3, 7.5, 17.5, 30, 40, 50, 60, 70, 80, 90};
    for (int i = 0; i < 10; ++i) {
        r.turbulenceToFlameSpeedRatio.addSample(i * 5.0, flameRatios[i]);
    }

    auto throttle = std::make_unique<DirectThrottleLinkage>();
    DirectThrottleLinkage::Parameters throttleParams{};
    throttleParams.gamma = 2.0;
    throttle->initialize(throttleParams);

    Engine::Parameters engineParams{};
    engineParams.name = "generic_crossplane_v8_ls_example_NON_HELLCAT";
    engineParams.cylinderBanks = 2;
    engineParams.cylinderCount = 8;
    engineParams.crankshaftCount = 1;
    engineParams.exhaustSystemCount = 2;
    engineParams.intakeCount = 1;
    engineParams.starterTorque = 200 * units::ft_lb;
    engineParams.starterSpeed = units::rpm(200);
    engineParams.redline = units::rpm(6500);
    engineParams.dynoMinSpeed = units::rpm(1000);
    engineParams.dynoMaxSpeed = units::rpm(6500);
    engineParams.dynoHoldStep = units::rpm(100);
    engineParams.initialSimulationFrequency = 10000;
    engineParams.initialHighFrequencyGain = 0.01;
    engineParams.initialNoise = 1.0;
    engineParams.initialJitter = 0.6;
    engineParams.throttle = throttle.get();
    engine.initialize(engineParams);
    throttle.release(); // Engine::destroy owns the throttle from this point.
    engineInitialized_ = true;

    constexpr double stroke = 3.622 * units::inch;
    constexpr double bore = 3.78 * units::inch;
    constexpr double rodLength = 160 * units::mm;
    constexpr double compressionHeight = 1.0 * units::inch;
    constexpr double crankMass = 60 * units::lb;
    constexpr double flywheelMass = 30 * units::lb;
    constexpr double flywheelRadius = 8 * units::inch;
    Crankshaft *crank = engine.getCrankshaft(0);
    Crankshaft::Parameters crankParams{};
    crankParams.mass = crankMass;
    crankParams.flywheelMass = flywheelMass;
    crankParams.momentOfInertia =
        1.5 * 0.5 * crankMass * stroke * stroke
        + 0.5 * flywheelMass * flywheelRadius * flywheelRadius
        + 0.5 * units::kg * units::cm * units::cm;
    crankParams.crankThrow = stroke / 2;
    crankParams.tdc = 45 * units::deg;
    crankParams.frictionTorque = 20 * units::ft_lb;
    crankParams.rodJournals = 4;
    crank->initialize(crankParams);
    const double journalDegrees[4] = {0, 270, 90, 180};
    for (int j = 0; j < 4; ++j) {
        crank->setRodJournalAngle(j, journalDegrees[j] * units::deg);
    }

    Intake::Parameters intakeParams{};
    intakeParams.volume = 1.325 * units::L;
    intakeParams.CrossSectionArea = 20 * units::cm2;
    intakeParams.InputFlowK = GasSystem::k_carb(700);
    intakeParams.IdleFlowK = GasSystem::k_carb(0);
    intakeParams.RunnerFlowRate = GasSystem::k_carb(100);
    intakeParams.IdleThrottlePlatePosition = 0.996;
    intakeParams.RunnerLength = 12 * units::inch;
    intakeParams.VelocityDecay = 0.5;
    engine.getIntake(0)->initialize(intakeParams);

    for (int bankIndex = 0; bankIndex < 2; ++bankIndex) {
        ExhaustSystem::Parameters exhaustParams{};
        exhaustParams.length = (bankIndex == 0 ? 100 : 172) * units::inch;
        // circle_area takes a radius, matching the script default exactly.
        exhaustParams.collectorCrossSectionArea =
            constants::pi * (2 * units::inch) * (2 * units::inch);
        exhaustParams.outletFlowRate = GasSystem::k_carb(1000);
        exhaustParams.primaryTubeLength = 29 * units::inch;
        exhaustParams.primaryFlowRate = GasSystem::k_carb(500);
        exhaustParams.velocityDecay = 1.0;
        exhaustParams.audioVolume = 4.0;
        exhaustParams.impulseResponse = nullptr; // No third-party WAV/IR asset.
        engine.getExhaustSystem(bankIndex)->initialize(exhaustParams);

        CylinderBank *bank = engine.getCylinderBank(bankIndex);
        CylinderBank::Parameters bankParams{};
        bankParams.crankshaft = crank;
        bankParams.angle = (bankIndex == 0 ? -45 : 45) * units::deg;
        bankParams.bore = bore;
        bankParams.deckHeight = stroke / 2 + rodLength + compressionHeight;
        bankParams.displayDepth = 0.5;
        bankParams.cylinderCount = 4;
        bankParams.index = bankIndex;
        bank->initialize(bankParams);

        for (int cylinder = 0; cylinder < 4; ++cylinder) {
            const int globalCylinder = bankIndex * 4 + cylinder;
            Piston *piston = engine.getPiston(globalCylinder);
            ConnectingRod *rod = engine.getConnectingRod(globalCylinder);
            Piston::Parameters pistonParams{};
            pistonParams.Rod = rod;
            pistonParams.Bank = bank;
            pistonParams.CylinderIndex = cylinder;
            pistonParams.BlowbyFlowCoefficient = GasSystem::k_28inH2O(0);
            pistonParams.CompressionHeight = compressionHeight;
            pistonParams.mass = 100 * units::g;
            piston->initialize(pistonParams);

            ConnectingRod::Parameters rodParams{};
            rodParams.mass = 50 * units::g;
            rodParams.momentOfInertia = rodParams.mass * rodLength * rodLength / 12;
            rodParams.length = rodLength;
            rodParams.piston = piston;
            rodParams.crankshaft = crank;
            rodParams.journal = cylinder;
            rod->initialize(rodParams);
        }

        Camshaft::Parameters camParams{};
        camParams.lobes = 4;
        camParams.crankshaft = crank;
        camParams.lobeProfile = &r.intakeLobe;
        camParams.baseRadius = 1 * units::inch;
        r.intakeCams[bankIndex].initialize(camParams);
        camParams.lobeProfile = &r.exhaustLobe;
        r.exhaustCams[bankIndex].initialize(camParams);
        for (int cylinder = 0; cylinder < 4; ++cylinder) {
            const double phase = firingSlot[bankIndex][cylinder] * 90 * units::deg;
            r.intakeCams[bankIndex].setLobeCenterline(cylinder, 476 * units::deg + phase);
            r.exhaustCams[bankIndex].setLobeCenterline(cylinder, 244 * units::deg + phase);
        }
        StandardValvetrain::Parameters valveParams{};
        valveParams.intakeCamshaft = &r.intakeCams[bankIndex];
        valveParams.exhaustCamshaft = &r.exhaustCams[bankIndex];
        r.valvetrains[bankIndex].initialize(valveParams);

        CylinderHead *head = engine.getHead(bankIndex);
        CylinderHead::Parameters headParams{};
        headParams.Bank = bank;
        headParams.ExhaustPortFlow = &r.exhaustFlow;
        headParams.IntakePortFlow = &r.intakeFlow;
        headParams.Valvetrain = &r.valvetrains[bankIndex];
        headParams.CombustionChamberVolume = 90 * units::cc;
        headParams.IntakeRunnerVolume = 149.6 * units::cc;
        headParams.IntakeRunnerCrossSectionArea = (2.2 * units::inch) * (2.2 * units::inch);
        headParams.ExhaustRunnerVolume = 50 * units::cc;
        headParams.ExhaustRunnerCrossSectionArea = (1.75 * units::inch) * (1.75 * units::inch);
        headParams.FlipDisplay = bankIndex == 1;
        head->initialize(headParams);
        for (int cylinder = 0; cylinder < 4; ++cylinder) {
            head->setIntake(cylinder, engine.getIntake(0));
            head->setExhaustSystem(cylinder, engine.getExhaustSystem(bankIndex));
            head->setSoundAttenuation(cylinder, 1.0);
            head->setHeaderPrimaryLength(cylinder,
                (3 - cylinder) * 2 * units::inch + primaryExtraCm[bankIndex][cylinder] * units::cm);
        }
    }

    IgnitionModule::Parameters ignitionParams{};
    ignitionParams.cylinderCount = 8;
    ignitionParams.crankshaft = crank;
    ignitionParams.timingCurve = &r.timingCurve;
    ignitionParams.revLimit = units::rpm(6800);
    ignitionParams.limiterDuration = 0.2;
    engine.getIgnitionModule()->initialize(ignitionParams);
    for (int bank = 0; bank < 2; ++bank) {
        for (int cylinder = 0; cylinder < 4; ++cylinder) {
            engine.getIgnitionModule()->setFiringOrder(
                bank * 4 + cylinder, firingSlot[bank][cylinder] * 90 * units::deg);
        }
    }
    engine.getIgnitionModule()->m_enabled = false; // The harness owns ignition/starter control.

    Fuel::Parameters fuelParams{};
    fuelParams.name = "generic gasoline / upstream LS example";
    fuelParams.maxBurningEfficiency = 1.0;
    fuelParams.maxDilutionEffect = 10.0; // objects.mr default, unlike the C++ default of 50.
    fuelParams.turbulenceToFlameSpeedRatio = &r.turbulenceToFlameSpeedRatio;
    engine.getFuel()->initialize(fuelParams);
    CombustionChamber::Parameters chamberParams{};
    chamberParams.Fuel = engine.getFuel();
    chamberParams.MeanPistonSpeedToTurbulence = &r.meanPistonSpeedToTurbulence;
    chamberParams.StartingPressure = units::atm;
    chamberParams.StartingTemperature = units::celcius(25);
    chamberParams.CrankcasePressure = units::atm;
    for (int i = 0; i < 8; ++i) {
        chamberParams.Piston = engine.getPiston(i);
        chamberParams.Head = engine.getHead(i / 4);
        engine.getChamber(i)->initialize(chamberParams);
    }

    engine.calculateDisplacement();
    engine.setSpeedControl(0.0);
    engine.setThrottle(1.0);
}

void OfflineModel::destroy() {
    if (engineInitialized_) {
        // Upstream Engine::destroy does not call CylinderHead::destroy.
        for (int bank = 0; bank < engine.getCylinderBankCount(); ++bank) {
            engine.getHead(bank)->destroy();
        }
        engine.destroy();
        engineInitialized_ = false;
    }
    resources_.reset();
}
