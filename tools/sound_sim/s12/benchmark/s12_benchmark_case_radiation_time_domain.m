function acceptance = acceptCase(metrics)
if metrics.execution_mode == "unified_evidence"
    checks = [ ...
        check("unified_retry_rollback", metrics.evidence_passed, ...
            double(~metrics.evidence_passed), 0), ...
        check("state_rollback_exact", metrics.state_rollback_error == 0, ...
            metrics.state_rollback_error, 0), ...
        check("radiation_rollback_exact", metrics.radiation_rollback_error == 0, ...
            metrics.radiation_rollback_error, 0), ...
        check("reset_exact", metrics.reset_state_error == 0 && ...
            metrics.reset_radiation_error == 0, ...
            max(metrics.reset_state_error, metrics.reset_radiation_error), 0)];
else
    limits = metrics.acceptance_limits;
    checks = [ ...
        check("finite", all(isfinite(metrics.minimum_density)) && ...
            all(isfinite(metrics.minimum_pressure)), 0, 0), ...
        check("zero_input_decay", metrics.zero_input_decay_observed, ...
            double(~metrics.zero_input_decay_observed), 0), ...
        check("positive_density", min(metrics.minimum_density) >= limits.minimum_density, ...
            min(metrics.minimum_density), limits.minimum_density), ...
        check("positive_pressure", min(metrics.minimum_pressure) >= limits.minimum_pressure, ...
            min(metrics.minimum_pressure), limits.minimum_pressure), ...
        check("maximum_cfl", max(metrics.maximum_cfl) <= limits.maximum_cfl, ...
            max(metrics.maximum_cfl), limits.maximum_cfl), ...
        check("nominal_retry", max(metrics.retry_count) <= limits.maximum_retry_count, ...
            max(metrics.retry_count), limits.maximum_retry_count), ...
        check("no_rejected_step", max(metrics.rejected_step_count) == 0, ...
            max(metrics.rejected_step_count), 0), ...
        check("no_clipping", max(metrics.clipping_count) == 0, ...
            max(metrics.clipping_count), 0), ...
        check("no_fallback", max(metrics.flux_fallback_count) == 0, ...
            max(metrics.flux_fallback_count), 0), ...
        check("pole_amplification", max(metrics.maximum_ssprk_amplification) <= ...
            limits.maximum_radiation_stage_pole_amplification, ...
            max(metrics.maximum_ssprk_amplification), ...
            limits.maximum_radiation_stage_pole_amplification), ...
        check("time_step_margin", min(metrics.radiation_time_step_margin) >= ...
            limits.minimum_time_step_margin, min(metrics.radiation_time_step_margin), ...
            limits.minimum_time_step_margin), ...
        check("reflection_complex", max(metrics.reflection_complex_error) <= ...
            limits.maximum_complex_reflection_error, ...
            max(metrics.reflection_complex_error), limits.maximum_complex_reflection_error), ...
        check("reflection_magnitude", max(metrics.reflection_magnitude_error) <= ...
            limits.maximum_reflection_magnitude_error, ...
            max(metrics.reflection_magnitude_error), limits.maximum_reflection_magnitude_error), ...
        check("reflection_phase", max(metrics.reflection_phase_error) <= ...
            limits.maximum_reflection_phase_error, ...
            max(metrics.reflection_phase_error), limits.maximum_reflection_phase_error), ...
        check("waveform_l1", max(metrics.waveform_l1_error) <= limits.maximum_waveform_l1, ...
            max(metrics.waveform_l1_error), limits.maximum_waveform_l1), ...
        check("waveform_linf", max(metrics.waveform_linf_error) <= limits.maximum_waveform_linf, ...
            max(metrics.waveform_linf_error), limits.maximum_waveform_linf), ...
        check("arrival", max(metrics.arrival_time_error) <= limits.maximum_arrival_time_error_s, ...
            max(metrics.arrival_time_error), limits.maximum_arrival_time_error_s), ...
        check("prearrival", max(metrics.prearrival_reflection_metric) <= ...
            limits.maximum_prearrival_reflection, ...
            max(metrics.prearrival_reflection_metric), limits.maximum_prearrival_reflection), ...
        check("energy", max(metrics.energy_balance_residual) <= limits.maximum_energy_residual, ...
            max(metrics.energy_balance_residual), limits.maximum_energy_residual), ...
        check("linearity", metrics.amplitude_linearity_error <= ...
            limits.maximum_amplitude_linearity_error, metrics.amplitude_linearity_error, ...
            limits.maximum_amplitude_linearity_error), ...
        convergenceCheck("grid_order", metrics.observed_grid_order, ...
            limits.minimum_grid_order), ...
        convergenceCheck("time_order", metrics.observed_time_order, ...
            limits.minimum_time_order)];
end
acceptance = struct("status", "failed", "checks", checks);
if all([checks.passed]), acceptance.status = "passed"; end
end

function value = convergenceCheck(id, values, limit)
finite = values(isfinite(values));
if isempty(finite)
    value = check(id, true, NaN, limit);
else
    value = check(id, max(finite) >= limit, max(finite), limit);
end
end

