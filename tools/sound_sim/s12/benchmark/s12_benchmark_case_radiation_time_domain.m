end

function signal = normalizeInputSignal(value)
if isempty(value)
    signal = struct();
    return
end
signal = value;
while iscell(signal)
    if ~isscalar(signal)
        error("S12:Radiation:InvalidInput", "Case input_signal must be one object.");
    end
    signal = signal{1};
    if isempty(signal)
        signal = struct();
        return
    end
end
if ~isstruct(signal) || ~isscalar(signal)
    error("S12:Radiation:InvalidInput", "Case input_signal must be an object.");
end
end

function value = inputFrequency(signal)
if isempty(fieldnames(signal)), value = NaN; return, end
if isfield(signal, "frequency_hz"), value = reshape(signal.frequency_hz, 1, []); return, end
if isfield(signal, "start_frequency_hz")
    value = [signal.start_frequency_hz, signal.end_frequency_hz];
else
    value = NaN;
end
end

function value = fieldOr(input, name, fallback)
if isfield(input, name), value = input.(name); else, value = fallback; end
end

function hash = limitHash(boundaryLimit)
digest = java.security.MessageDigest.getInstance("SHA-256");
digest.update(uint8(char("radiation_limit|" + boundaryLimit)));
bytes = typecast(digest.digest(), "uint8");
hash = string(upper(reshape(dec2hex(bytes, 2).', 1, [])));
end

function pressure = minimumPressureOf(state, gamma)
density = state(1, :); velocity = state(2, :) ./ density;
pressure = min((gamma - 1) * (state(3, :) - 0.5 * density .* velocity.^2));
end

