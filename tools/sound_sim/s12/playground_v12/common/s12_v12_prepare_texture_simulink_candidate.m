function plan = s12_v12_prepare_texture_simulink_candidate(sourceModel, outputModel)
%S12_V12_PREPARE_TEXTURE_SIMULINK_CANDIDATE Describe a controlled model copy.
% Actual structural edits must run through model_edit in an existing MATLAB
% session. This function never overwrites a source model or creates a claim.

arguments
    sourceModel (1,1) string
    outputModel (1,1) string
end
if strlength(sourceModel) == 0 || strlength(outputModel) == 0 || sourceModel == outputModel
    error("S12:EngineSoundV12:Candidate", "Source and output model paths must be distinct.");
end
if ~isfile(sourceModel)
    error("S12:EngineSoundV12:Candidate", "Source model is missing.");
end
contract = s12_v12_texture_simulink_contract();
plan = struct( ...
    "status", "READY_FOR_EXISTING_SESSION_MODEL_EDIT", ...
    "source_model", sourceModel, ...
    "output_model", outputModel, ...
    "source_sha256", "NOT_COMPUTED_WITHOUT_RUNTIME", ...
    "contract", contract, ...
    "operations", [ ...
        "copy source model to isolated candidate", ...
        "add Texture Residual Inport [960,1]", ...
        "add Texture Weight Inport [1,1]", ...
        "add Texture Mixer MATLAB Function s12_v12_model_texture_step [960,1]", ...
        "connect mixer before Frozen Radiation Adapter", ...
        "preserve default weight=0 and old route", ...
        "cold reload/update diagram/active compile", ...
        "run 90s deterministic simulation twice"], ...
    "qualification", "INSUFFICIENT_EVIDENCE_UNTIL_RUNTIME_AND_ACOUSTIC_GATES");
end
